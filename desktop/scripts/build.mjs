// Bundles the renderer (esbuild), generates the icon map and copies fonts / templates into dist/.
import * as esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const watch = process.argv.includes('--watch');
fs.mkdirSync(path.join(dist, 'fonts'), { recursive: true });
fs.mkdirSync(path.join(dist, 'templates'), { recursive: true });

// --- icon map: every lucide icon name referenced in a string literal in src/
const iconDir = path.join(root, 'node_modules/lucide-static/icons');
const available = new Set(fs.readdirSync(iconDir).map((f) => f.replace(/\.svg$/, '')));
const used = new Set(['circle']);
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (/\.js$/.test(e.name) && !e.name.includes('.gen.')) for (const m of fs.readFileSync(p, 'utf8').matchAll(/['"]([a-z0-9]+(?:-[a-z0-9]+)*)['"]/g)) if (available.has(m[1])) used.add(m[1]); } };
walk(path.join(root, 'src'));
let out = '// generated by scripts/build.mjs – lucide icons (ISC licence)\nexport default {\n';
for (const n of [...used].sort()) {
  const svg = fs.readFileSync(path.join(iconDir, n + '.svg'), 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/\s*\n\s*/g, ' ').replace(/ class="[^"]*"/, '').trim();
  out += `  ${JSON.stringify(n)}: ${JSON.stringify(svg)},\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'src/ui/icons.gen.js'), out);
console.log(`icons: ${used.size}`);

// --- static files
for (const f of ['index.html', 'styles.css']) fs.copyFileSync(path.join(root, 'src', f), path.join(dist, f));
const fontPkgs = ['michroma', 'orbitron', 'audiowide', 'russo-one', 'bungee', 'bebas-neue', 'anton', 'montserrat', 'inter', 'roboto-slab', 'lobster', 'pacifico', 'press-start-2p', 'jetbrains-mono'];
for (const f of fontPkgs) {
  const dir = path.join(root, 'node_modules/@fontsource', f, 'files');
  const pick = (w) => fs.readdirSync(dir).find((x) => x === `${f}-latin-${w}-normal.woff`);
  const file = pick('700') && ['montserrat', 'inter', 'roboto-slab'].includes(f) ? pick('700') : pick('400') || fs.readdirSync(dir).find((x) => /latin-\d+-normal\.woff$/.test(x));
  fs.copyFileSync(path.join(dir, file), path.join(dist, 'fonts', f + '.woff'));
}
for (const w of [400, 500, 600, 700]) fs.copyFileSync(path.join(root, `node_modules/@fontsource/inter/files/inter-latin-${w}-normal.woff2`), path.join(dist, 'fonts', `inter-latin-${w}-normal.woff2`));
for (const f of fs.readdirSync(path.join(root, 'assets/templates'))) fs.copyFileSync(path.join(root, 'assets/templates', f), path.join(dist, 'templates', f));
const licence = 'Bundled fonts are licensed under the SIL Open Font License 1.1 (see https://openfontlicense.org). Icons: Lucide (ISC).\n';
fs.writeFileSync(path.join(dist, 'fonts', 'LICENSES.txt'), licence);

const opts = {
  entryPoints: [path.join(root, 'src/app.js')], bundle: true, outfile: path.join(dist, 'app.js'), format: 'iife', target: 'chrome120',
  minify: !watch, sourcemap: watch ? 'inline' : false, logLevel: 'info', legalComments: 'none',
  loader: { '.wasm': 'binary' },
};
if (watch) { const ctx = await esbuild.context(opts); await ctx.watch(); } else await esbuild.build(opts);
